export function editorUserPrompt(text: string, feedback?: string): string {
  const base = `راجع الرسالة التالية وأعد قائمة التعديلات:\n<message>\n${text}\n</message>`;
  if (!feedback) return base;
  return `${base}\n\nملاحظات على محاولتك السابقة، صحّحها:\n${feedback}`;
}

